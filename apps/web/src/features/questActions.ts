import { generateQuest } from '@lifequest/ai';
import { addSpecialQuest, fallbackQuest, rerollQuest, rerollsLeft, type Quest } from '@lifequest/core';
import { useState } from 'react';
import type { Ctx } from './types';

/** Shared handlers for daily/boss claiming and quest re-rolls. */
export function useQuestActions(ctx: Ctx) {
  const { state, setState, ai, toast } = ctx;
  const [busy, setBusy] = useState<string | null>(null);

  const input = (goal: string, extraRecent: string[] = []) => ({
    goal,
    interests: state.profile!.interests,
    existingSkills: state.skills.map((k) => k.name),
    recentCompleted: [...state.quests.filter((q) => q.status === 'completed').map((q) => q.title), ...extraRecent],
  });
  const note = (source: 'ai' | 'fallback') => (source === 'ai' ? '✨ Generated by your AI Game Master.' : 'Offline Game Master used.');

  async function claim(kind: 'daily' | 'boss') {
    if (busy) return;
    setBusy(kind);
    const res = await generateQuest(kind, input(state.profile!.goals[0] ?? 'a better life'), ai);
    setState((s) => addSpecialQuest(s, kind, res.quest));
    toast(`${kind === 'daily' ? '🌅 Daily quest' : '🐉 Weekly boss'} unlocked. ${note(res.source)}`);
    setBusy(null);
  }

  async function reroll(q: Quest) {
    if (busy) return;
    if (rerollsLeft(state) <= 0) return toast('No re-rolls left today. They refresh tomorrow.');
    setBusy(q.id);
    const goal = state.adventures.find((a) => a.id === q.adventureId)?.goal ?? q.action;
    let res = await generateQuest('reroll', input(goal, [q.title]), ai);
    // a re-roll must change something: retry the small offline pool (or an identical AI answer) a few times
    for (let i = 0; i < 6 && res.quest.title === q.title; i++) res = { ...res, source: 'fallback', quest: fallbackQuest(q.kind === 'boss' ? 'boss' : 'daily') };
    setState((s) => { const r = rerollQuest(s, q.id, res.quest); return r.ok ? r.state : s; });
    toast(`🎲 Quest re-rolled. ${note(res.source)}`);
    setBusy(null);
  }

  return { busy, claim, reroll, rerollsLeft: rerollsLeft(state) };
}
