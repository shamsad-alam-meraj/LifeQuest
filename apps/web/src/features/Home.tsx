'use client';

import AppLink from '../components/AppLink';
import { generateAdventure } from '@lifequest/ai';
import { addAdventure, canClaimDaily, canSpawnBoss, completedOn, isUnlocked, dayKey, levelProgress, streakDays, titleForLevel, totalXp, type Quest } from '@lifequest/core';
import { useState } from 'react';
import { Fox } from '../ui/Fox';
import { Icon } from '../ui/Icon';
import { ACHIEVEMENTS } from '@lifequest/core';
import { useQuestFlows } from './QuestFlows';
import { useQuestActions } from './questActions';
import { CustomQuestDialog } from './CustomQuestDialog';
import { QuestCard } from './QuestCard';
import type { Ctx } from './types';

export function Home(ctx: Ctx) {
  const { state, setState, ai, toast } = ctx;
  const profile = state.profile!;
  const [goal, setGoal] = useState('');
  const [busy, setBusy] = useState(false);
  const flows = useQuestFlows(ctx);
  const [writing, setWriting] = useState(false);
  const actions = useQuestActions(ctx);

  const xp = totalXp(state);
  const p = levelProgress(xp);
  const today = completedOn(state, dayKey(new Date().toISOString())).length;
  const active = state.quests.filter((q) => q.status === 'active').sort((a, b) => Number(isUnlocked(state, b)) - Number(isUnlocked(state, a)) || ((b.kind === 'boss' ? 2 : b.kind === 'daily' ? 1 : 0) - (a.kind === 'boss' ? 2 : a.kind === 'daily' ? 1 : 0)));
  const shown = active.slice(0, 5);
  const doneTotal = state.quests.filter((q) => q.status === 'completed').length;
  const idx = (q: Quest) => state.skills.findIndex((k) => k.id === q.skillId);
  const name = (q: Quest) => state.skills[idx(q)]?.name ?? '';

  async function create(g: string) {
    if (!g.trim() || busy) return;
    setBusy(true);
    const res = await generateAdventure({ goal: g, interests: profile.interests, existingSkills: state.skills.map((k) => k.name), recentCompleted: state.quests.filter((q) => q.status === 'completed').map((q) => q.title) }, ai);
    setState((s) => addAdventure(s, g, res.draft));
    setGoal('');
    toast(res.source === 'ai' ? '✨ New adventure generated by your AI Game Master.' : res.error ? `AI unavailable (${res.error.slice(0, 90)}). Used the offline Game Master.` : 'Offline Game Master used. Add a free API key in Settings for personalised quests.');
    setBusy(false);
  }

  const Stat = ({ icon, label, value, tone }: { icon: string; label: string; value: string | number; tone: string }) => (
    <div className="card flex items-center gap-3 p-4">
      <div className={`grid size-11 shrink-0 place-items-center rounded-xl text-lg ${tone}`}>{icon}</div>
      <div className="min-w-0"><p className="truncate font-display text-xl leading-none">{value}</p><p className="mt-1 text-xs text-ink2">{label}</p></div>
    </div>
  );
  const recent = [...state.achievements].slice(-4).reverse();

  return (
    <div className="grid gap-6 xl:grid-cols-[minmax(0,1fr)_400px] 2xl:grid-cols-[minmax(0,1fr)_460px]">
      <div className="flex min-w-0 flex-col gap-6">
        <section className="relative">
          <div className="pr-28 sm:pr-44">
            <h1 className="text-3xl sm:text-4xl 2xl:text-5xl">Ready, {profile.name}?</h1>
            <p className="mt-1 text-ink2">Let’s make today legendary.</p>
          </div>
          <div className="absolute -top-3 right-0 sm:-top-6"><Fox size={120} gear={state.equipped} /></div>
          <div className="card mt-5 flex items-center gap-4">
            <div className="min-w-0 flex-1">
              <p className="font-display text-xl"><span className="text-sm text-ink3">LVL</span> {p.level} <span className="ml-1 font-sans text-sm font-medium text-ink2">{titleForLevel(p.level)}</span></p>
              <div className="bar my-2"><i style={{ width: `${p.fraction * 100}%` }} /></div>
              <p className="text-right text-xs text-ink2">{p.intoLevel}/{p.forNext} XP to next level</p>
            </div>
          </div>
        </section>

        <section aria-label="Daily challenges" className="grid gap-3 sm:grid-cols-2">
          <div className="card flex items-center gap-3 p-4">
            <div className="grid size-12 shrink-0 place-items-center rounded-xl bg-grad-gold text-2xl">🌅</div>
            <div className="min-w-0 flex-1"><p className="font-display text-lg leading-tight">Quest of the Day</p><p className="text-xs text-ink2">{canClaimDaily(state) ? '1.5× XP. A fresh challenge, once a day.' : 'Claimed. Come back tomorrow.'}</p></div>
            <button className="btn btn-gold px-4" disabled={!canClaimDaily(state) || !!actions.busy} onClick={() => void actions.claim('daily')}>{actions.busy === 'daily' ? '…' : canClaimDaily(state) ? 'Claim' : '✓'}</button>
          </div>
          <div className="card flex items-center gap-3 p-4">
            <div className="grid size-12 shrink-0 place-items-center rounded-xl bg-grad-violet text-2xl">🐉</div>
            <div className="min-w-0 flex-1"><p className="font-display text-lg leading-tight">Weekly Boss</p><p className="text-xs text-ink2">{canSpawnBoss(state) ? '3× XP. One big challenge a week.' : 'Summoned this week. A new one next week.'}</p></div>
            <button className="btn btn-primary px-4" disabled={!canSpawnBoss(state) || !!actions.busy} onClick={() => void actions.claim('boss')}>{actions.busy === 'boss' ? '…' : canSpawnBoss(state) ? 'Summon' : '✓'}</button>
          </div>
        </section>

        <section aria-label="Stats" className="grid grid-cols-2 gap-3 lg:grid-cols-4">
          <Stat icon="🔥" label={`Day streak${(state.shields ?? 0) ? ` · 🛡️ ${state.shields}` : ''}`} value={streakDays(state)} tone="bg-grad-violet" />
          <Stat icon="⭐" label="Total XP" value={xp} tone="bg-grad-gold text-[#3a2300]" />
          <Stat icon="✅" label="Quests done" value={doneTotal} tone="bg-grad-teal" />
          <Stat icon="📅" label="Rewarded today" value={`${today}/${profile.dailyQuestLimit}`} tone="bg-grad-blue" />
        </section>

        <section aria-labelledby="today">
          <div className="mb-3 flex items-baseline justify-between"><h2 id="today" className="text-xl">Today’s Quests</h2><span className="text-sm text-ink2">{active.length} active</span></div>
          <div className="grid gap-3 2xl:grid-cols-2">
            {shown.length === 0 && <div className="card text-center text-ink2 2xl:col-span-2">No active quests. Name a goal and your Game Master will craft an adventure.</div>}
            {shown.map((q) => <QuestCard key={q.id} q={q} skillName={name(q)} skillIndex={idx(q)} locked={!isUnlocked(state, q)} rerolling={actions.busy === q.id} onOpen={() => flows.openComplete(q)} onFocus={() => flows.openFocus(q)} onReroll={q.kind === 'custom' ? undefined : () => void actions.reroll(q)} />)}
          </div>
          {active.length > shown.length && <AppLink href="/app/adventures" className="mt-3 block text-center text-sm font-semibold text-gold no-underline">View all {active.length} active quests →</AppLink>}
        </section>
      </div>

      <aside className="flex min-w-0 flex-col gap-6">
        <section className="card flex flex-col gap-3" aria-labelledby="newadv">
          <h2 id="newadv" className="text-lg">New adventure</h2>
          <form className="flex flex-col gap-3 sm:flex-row xl:flex-col" onSubmit={(e) => { e.preventDefault(); void create(goal); }}>
            <input className="input" value={goal} onChange={(e) => setGoal(e.target.value)} placeholder="What do you want to achieve in real life?" aria-label="Goal" />
            <button className="btn btn-primary shrink-0" disabled={busy || !goal.trim()}>{busy ? 'Conjuring…' : 'Generate'}</button>
          </form>
          {profile.goals.length > 0 && <div className="flex flex-wrap gap-2">{profile.goals.map((g) => <button key={g} className="pill min-h-8 cursor-pointer px-3 hover:bg-white/10" disabled={busy} onClick={() => void create(g)}>+ {g}</button>)}</div>}
          <button className="btn btn-ghost justify-start px-0 text-sm text-gold" onClick={() => setWriting(true)}>🛠️ Write your own quest</button>
          <p className="text-xs text-ink3">{ai ? 'Powered by your AI Game Master.' : 'Offline Game Master. Add a free API key in Settings for personalised quests.'}</p>
        </section>

        <section className="card flex flex-col gap-3" aria-labelledby="trophies">
          <div className="flex items-baseline justify-between"><h2 id="trophies" className="text-lg">Recent trophies</h2><AppLink href="/app/trophies" className="text-xs font-semibold text-gold no-underline">{state.achievements.length}/{ACHIEVEMENTS.length}</AppLink></div>
          {recent.length === 0 ? <p className="text-sm text-ink2">Complete your first quest to unlock a trophy.</p> : (
            <ul className="m-0 flex list-none flex-col gap-2 p-0">{recent.map((a) => <li key={a.id} className="flex items-center gap-3 rounded-xl bg-white/5 px-3 py-2.5"><span className="text-2xl">{a.icon}</span><div><p className="text-sm font-semibold">{a.title}</p><p className="text-xs text-ink2">{a.description}</p></div></li>)}</ul>
          )}
        </section>
      </aside>

      {flows.node}
      {writing && <CustomQuestDialog ctx={ctx} onClose={() => setWriting(false)} />}
    </div>
  );
}
